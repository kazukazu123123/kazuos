pub struct UiSurface {
    address: u64,
    pub width: i32,
    pub height: i32,
    pub stride: i32,
    pub format: u32,
}

impl UiSurface {
    pub fn new(address: u64, width: u32, height: u32, stride: u32, format: u32) -> Self {
        Self { address, width: width as i32, height: height as i32, stride: stride as i32, format }
    }
    pub fn pack(&self, r: u8, g: u8, b: u8) -> u32 {
        if self.format == GUI_PIXEL_FORMAT_BGRX8888 { (b as u32) << 16 | (g as u32) << 8 | r as u32 }
        else { (r as u32) << 16 | (g as u32) << 8 | b as u32 }
    }
    pub fn put(&mut self, x: i32, y: i32, color: u32) {
        if x < 0 || y < 0 || x >= self.width || y >= self.height { return; }
        unsafe { (self.address as *mut u32).add((y * self.stride + x) as usize).write_volatile(color); }
    }
    pub fn clear(&mut self, color: u32) { self.fill(0, 0, self.width, self.height, color); }
    pub fn fill(&mut self, x: i32, y: i32, width: i32, height: i32, color: u32) {
        let x0 = x.max(0); let y0 = y.max(0); let x1 = (x + width).min(self.width); let y1 = (y + height).min(self.height);
        for yy in y0..y1 { for xx in x0..x1 { self.put(xx, yy, color); } }
    }
    pub fn frame(&mut self, x: i32, y: i32, width: i32, height: i32, color: u32) {
        self.fill(x, y, width, 1, color); self.fill(x, y + height - 1, width, 1, color);
        self.fill(x, y, 1, height, color); self.fill(x + width - 1, y, 1, height, color);
    }
    pub fn glyph(&mut self, x: i32, y: i32, byte: u8, color: u32) {
        if !(0x20..=0x7e).contains(&byte) { return; }
        let base = (byte - 0x20) as usize * UI_GLYPH_H as usize;
        for row in 0..UI_GLYPH_H { let bits = UI_FONT_7X14[base + row as usize]; for column in 0..UI_GLYPH_W {
            if bits & (0x80 >> column) != 0 { self.put(x + column, y + row, color); }
        }}
    }
    pub fn text(&mut self, mut x: i32, y: i32, bytes: &[u8], color: u32) {
        for byte in bytes { self.glyph(x, y, *byte, color); x += UI_ADVANCE; }
    }
    pub fn button(&mut self, x: i32, y: i32, width: i32, height: i32, label: &[u8], pressed: bool) {
        let bg = if pressed { self.pack(55, 100, 145) } else { self.pack(45, 55, 70) };
        let border = self.pack(95, 165, 220); self.fill(x, y, width, height, bg); self.frame(x, y, width, height, border);
        self.text(x + 8, y + (height - UI_GLYPH_H) / 2, label, self.pack(235, 240, 245));
    }
}

pub fn ui_u64(mut value: u64, output: &mut [u8; 24]) -> &[u8] {
    if value == 0 { output[0] = b'0'; return &output[..1]; }
    let mut length = 0; while value != 0 { output[length] = b'0' + (value % 10) as u8; value /= 10; length += 1; }
    output[..length].reverse(); &output[..length]
}
